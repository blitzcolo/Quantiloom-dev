#!/usr/bin/env python3
"""E6 -- fit a material parameter to a measured record, with the derivative.

Every number in a thermal material is a measurement of something, and some of
them are not measurable at the site: the convective coefficient is not a
property of the soil at all, it is a property of the wind over it, and the
literature offers a correlation rather than a value. So it gets fitted.

Fitting it by sweeping is what the solver could do before this. A sweep costs
one whole trajectory per candidate and gives a resolution equal to the sweep's
own step, and neither the cost nor the resolution improves when the answer
turns out to lie between two samples. A Gauss-Newton step costs one trajectory
and lands on the minimum of the local quadratic:

    p <- p + (J^T J)^-1 J^T r,    J_i = dT(t_i)/dp,    r_i = T_obs,i - T(t_i)

which is exactly what `[solve] parameter_sensitivities` puts in the column
tool's output. Three or four steps is convergence for a scalar, against
dozens of runs for a sweep of the same precision, and the same J gives the
standard error for free.

What it does NOT do is make the fitted number a measurement. A coefficient
fitted to one window is a summary of that window's weather; the split between
the window it was fitted on and the windows it is then tested against is what
says whether it is anything more, and that split is the caller's to declare.

Usage:
    e6_fit_h.py --forcing site.csv --observed obs.csv --out fit.json
    e6_fit_h.py --forcing site.csv --observed obs.csv --parameter k

`observed` is a two-column CSV of `time_h, T_K` on the forcing's own clock;
`#` comments and a non-numeric first line are skipped, as everywhere else here.
"""

import argparse
import json
import math
import pathlib
import subprocess
import sys

import numpy as np

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from runlog import REPO  # noqa: E402
from _winpaths import require_windows_paths  # noqa: E402

COLUMN = REPO / "build" / "src" / "tools" / "Release" / "thermal_column_tool.exe"

# Which spec key each parameter lives under, and the column the tool writes it
# in. The names are the solver's own -- see thermal::ThermalParameterName.
PARAMETERS = {
    "h":       {"key": "convection_h_w_m2k",        "column": "dTd_h",       "min": 0.1},
    "epsilon": {"key": "ir_emissivity",             "column": "dTd_epsilon", "min": 0.01,
                "max": 1.0},
    "alpha":   {"key": "shortwave_absorptivity",    "column": "dTd_alpha",   "min": 0.01,
                "max": 1.0},
    "k":       {"key": "thermal_conductivity_w_mk", "column": "dTd_k",       "min": 1e-3},
    "rhoc":    {"key": "density_kg_m3",             "column": "dTd_rhoc",    "min": 1.0},
}

# The soil the SURFRAD comparison uses, as e2_surfrad.py states it. Everything
# but the fitted parameter is held at these.
SOIL = {
    "thermal_conductivity_w_mk": 0.60,
    "density_kg_m3": 1500.0,
    "specific_heat_j_kgk": 1100.0,
    "thickness_m": 0.60,
    "convection_h_w_m2k": 20.0,
    "shortwave_absorptivity": 0.78,
    "ir_emissivity": 0.96,
}


def read_pairs(path):
    """A two-column numeric CSV, tolerant of comments and a header line."""
    times, values = [], []
    for line in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        parts = line.replace(",", " ").split()
        try:
            times.append(float(parts[0]))
            values.append(float(parts[1]))
        except (ValueError, IndexError):
            continue          # the header
    return np.array(times), np.array(values)


def write_spec(path, forcing, end_time_h, parameter, value, soil, output_step_h):
    """The column spec, with `parameter` set to `value` and its tangent asked for."""
    fields = dict(soil)
    # rho c is moved through the density, the way the solver's own knob does:
    # the pair is one number to the balance.
    fields[PARAMETERS[parameter]["key"]] = (
        value / fields["specific_heat_j_kgk"] if parameter == "rhoc" else value)

    path.write_text(f"""# Auto-generated by scripts/experiments/e6_fit_h.py
[column]
thermal_conductivity_w_mk = {fields['thermal_conductivity_w_mk']}
density_kg_m3             = {fields['density_kg_m3']}
specific_heat_j_kgk       = {fields['specific_heat_j_kgk']}
thickness_m               = {fields['thickness_m']}
convection_h_w_m2k        = {fields['convection_h_w_m2k']}
shortwave_absorptivity    = {fields['shortwave_absorptivity']}
ir_emissivity             = {fields['ir_emissivity']}
interior_bc               = "adiabatic"
interior_temperature_k    = 290.0

[solve]
start_time_h  = 0.0
end_time_h    = {end_time_h:.4f}
timestep_s    = 60.0
layers        = 10
initial       = "steady"
output_step_h = {output_step_h:.6f}
checkpoint_stride_h = 24.0
parameter_sensitivities = ["{parameter}"]

[geometry]
normal       = [0.0, 1.0, 0.0]
sky_fraction = 1.0

[forcing]
file = "{pathlib.Path(forcing).as_posix()}"
""", encoding="utf-8")


def run_column(spec, out_csv, column):
    """One trajectory: the predicted temperature and its derivative, per row."""
    result = subprocess.run([str(COLUMN), str(spec), "--out", str(out_csv)],
                            capture_output=True, text=True, encoding="utf-8",
                            errors="replace", timeout=3600)
    if result.returncode != 0:
        print(result.stdout + result.stderr, file=sys.stderr)
        raise SystemExit(f"{spec.name} failed")

    lines = [l for l in pathlib.Path(out_csv).read_text(encoding="utf-8").splitlines()
             if l.strip()]
    header = lines[0].split(",")
    if column not in header:
        raise SystemExit(f"{out_csv} has no {column} column; the solver was built "
                         f"without parameter_sensitivities support")
    rows = np.array([[float(v) if v.strip() else math.nan for v in l.split(",")]
                     for l in lines[1:]])
    return (rows[:, header.index("time_h")],
            rows[:, header.index("T_surface_K")],
            rows[:, header.index(column)])


def fit(args):
    times_obs, observed = read_pairs(args.observed)
    if times_obs.size < 10:
        raise SystemExit(f"{args.observed} has {times_obs.size} usable rows")

    spec_dir = pathlib.Path(args.work)
    spec_dir.mkdir(parents=True, exist_ok=True)
    bounds = PARAMETERS[args.parameter]
    value = args.start if args.start is not None else SOIL[bounds["key"]]
    if args.parameter == "rhoc":
        value = SOIL["density_kg_m3"] * SOIL["specific_heat_j_kgk"]

    # Evaluate on the observation's own cadence, so no interpolation of the
    # measurement is needed -- only of the prediction, which is smooth.
    output_step_h = float(np.median(np.diff(times_obs)))
    end_time_h = float(times_obs[-1])

    steps = []
    for iteration in range(args.iterations):
        spec = spec_dir / f"fit_{args.parameter}_{iteration}.toml"
        write_spec(spec, args.forcing, end_time_h, args.parameter, value, SOIL,
                   output_step_h)
        times, predicted, jacobian = run_column(
            spec, spec_dir / f"fit_{args.parameter}_{iteration}.csv", bounds["column"])

        # Only where the fit is asked to explain something: the spin-up is the
        # initial condition being forgotten, not the parameter being wrong.
        keep = times_obs >= args.evaluate_from_h
        model = np.interp(times_obs[keep], times, predicted)
        gradient = np.interp(times_obs[keep], times, jacobian)
        residual = observed[keep] - model

        rmse = float(np.sqrt(np.mean(residual ** 2)))
        denominator = float(gradient @ gradient)
        if denominator <= 0.0:
            print(f"  {args.parameter} = {value:.6g}: the trajectory does not "
                  f"respond to it here; stopping")
            break

        delta = float(gradient @ residual) / denominator
        steps.append({"iteration": iteration, "value": value, "rmse_k": rmse,
                      "step": delta, "points": int(keep.sum())})
        print(f"  {iteration}: {args.parameter} = {value:.6g}  RMSE {rmse:.4f} K  "
              f"step {delta:+.6g}")

        moved = value + delta
        moved = max(moved, bounds["min"])
        if "max" in bounds:
            moved = min(moved, bounds["max"])
        if abs(moved - value) <= args.tolerance * max(abs(value), 1e-12):
            value = moved
            break
        value = moved

    # The standard error the same Jacobian gives: sigma^2 (J^T J)^-1, with
    # sigma^2 the residual variance. It says how sharply the record pins the
    # parameter, not how right the model is.
    spec = spec_dir / f"fit_{args.parameter}_final.toml"
    write_spec(spec, args.forcing, end_time_h, args.parameter, value, SOIL, output_step_h)
    times, predicted, jacobian = run_column(
        spec, spec_dir / f"fit_{args.parameter}_final.csv", bounds["column"])
    keep = times_obs >= args.evaluate_from_h
    model = np.interp(times_obs[keep], times, predicted)
    gradient = np.interp(times_obs[keep], times, jacobian)
    residual = observed[keep] - model
    dof = max(int(keep.sum()) - 1, 1)
    variance = float(residual @ residual) / dof
    denominator = float(gradient @ gradient)
    standard_error = math.sqrt(variance / denominator) if denominator > 0.0 else None

    out = {
        "parameter": args.parameter,
        "fitted": value,
        "standard_error": standard_error,
        "rmse_k": float(np.sqrt(np.mean(residual ** 2))),
        "bias_k": float(np.mean(residual)),
        "points": int(keep.sum()),
        "evaluate_from_h": args.evaluate_from_h,
        "iterations": steps,
        "held_fixed": SOIL,
        "forcing": str(args.forcing),
        "observed": str(args.observed),
    }
    print(f"\n{args.parameter} = {value:.6g}"
          + (f" +/- {standard_error:.4g}" if standard_error else "")
          + f"   RMSE {out['rmse_k']:.4f} K over {out['points']} points")

    if args.out:
        pathlib.Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        pathlib.Path(args.out).write_text(json.dumps(out, indent=2), encoding="utf-8")
        print(f"wrote {args.out}")
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--forcing", required=True, type=pathlib.Path)
    parser.add_argument("--observed", required=True, type=pathlib.Path)
    parser.add_argument("--parameter", default="h", choices=sorted(PARAMETERS))
    parser.add_argument("--start", type=float, default=None,
                        help="starting value; the soil table's own by default")
    parser.add_argument("--iterations", type=int, default=8)
    parser.add_argument("--tolerance", type=float, default=1e-4,
                        help="relative step below which the fit has converged")
    parser.add_argument("--evaluate-from-h", type=float, default=48.0,
                        help="skip the spin-up: before this the residual is the "
                             "initial condition, not the parameter")
    parser.add_argument("--work", default="work_e6")
    parser.add_argument("--out", default=None)
    args = parser.parse_args()

    # Windows paths, because the column tool is a Windows binary: under WSL's
    # interpreter every one of these becomes a directory of that literal name.
    require_windows_paths(pathlib.Path(args.work), args.forcing, args.observed)
    if not COLUMN.is_file():
        raise SystemExit(f"{COLUMN} is not built")
    fit(args)


if __name__ == "__main__":
    main()
